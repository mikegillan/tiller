import { describe, expect, it } from 'vitest';
import type { ArchivedNode, Conversation } from '../shared/protocol.js';
import { buildConversation, buildIndex, buildPeerConversation, parseEnvelope, parseRecords, type TreeNode } from './conversation.js';
import type { SessionEvent } from './sessions.js';
import { parseTranscript } from './transcript.js';

const T = Date.parse('2026-10-24T10:00:00.000Z');
const at = (min: number) => T + min * 60_000;
const iso = (min: number) => new Date(at(min)).toISOString();
const ev = (min: number, type: string, id: string, data: Record<string, unknown> = {}): SessionEvent => ({ ts: at(min), type, id, ...data });
const env = (label: string, body: string, nonce = 'Ab12') => `--- TL MESSAGE ${nonce} ---\nfrom: ${label}\nreply-to: none\n${body}\n--- END TL MESSAGE ${nonce} ---`;
const jsonl = (...lines: unknown[]) => lines.map((l) => JSON.stringify(l)).join('\n');
/** A compact view of the items: kind, who, text, and minutes past T. */
const view = (c: Conversation) => c.items.map((i) => [i.kind, 'from' in i ? i.from : i.id, 'text' in i ? i.text : i.kind === 'outcome' ? i.outcome.outcome : undefined, i.at === undefined ? undefined : (i.at - T) / 60_000]);

// Tree: root r ("tiller"), its children c and s.
const events: SessionEvent[] = [
  ev(0, 'spawn', 'c', { parentId: 'r', title: 'Coalesce probes' }),
  ev(1.5, 'send', 'r', { from: 'c', outcome: 'delivered', messageId: 'm-up', text: 'Started' }),
  ev(2, 'send', 'c', { from: 'r', outcome: 'queued', messageId: 'm-down', text: 'Also cover tests.' }),
  ev(2.5, 'send', 'c', { from: 's', outcome: 'delivered', messageId: 'm-sib', text: 'hi from s' }),
  ev(4, 'settle', 'c', { messageId: 'm-down', from: 'r', outcome: 'delivered' }),
  ev(6, 'send', 'r', { from: 'tiller', outcome: 'delivered', messageId: 'm-n1', text: 'No hook event for 7m.', label: 'tiller (child c "Coalesce probes" no activity)', about: ['c'] }),
  ev(7, 'send', 'r', { from: 'tiller', outcome: 'delivered', messageId: 'm-n2', text: '2 of 2 finished', label: 'tiller (notify_when all of turn)', about: ['c', 's'] }),
  ev(7.5, 'send', 'r', { from: 'c', outcome: 'refused', messageId: 'm-ref', text: 'too many' }),
  ev(8, 'send', 'r', { from: 'c', outcome: 'delivered', messageId: 'm-old-up' }), // logged before text was recorded
  ev(8.5, 'send', 'c', { from: 'r', outcome: 'delivered', messageId: 'm-old-down' }),
  ev(10, 'outcome', 'c', { outcome: 'succeeded', summary: 'probes coalesced', gate: 'passed' }),
  ev(11, 'merge', 'c', { branch: 'tl/c', base: 'main', sha: 'abc1234', style: 'merge' }),
];
const records = parseRecords(events);

// Claude transcript of c: string-content envelopes, content-array assistant lines, tool results and noise.
const claude = jsonl(
  { type: 'user', timestamp: iso(0.01), message: { role: 'user', content: 'Build the thing.' } },
  { type: 'assistant', timestamp: iso(1), message: { content: [{ type: 'text', text: 'Starting.' }, { type: 'tool_use', name: 'mcp__tiller__send', input: { nodeId: 'r', text: 'Started' } }] } },
  { type: 'user', timestamp: iso(1.1), message: { content: [{ type: 'tool_result', tool_use_id: 'x', content: 'delivered' }] } },
  { type: 'attachment', timestamp: iso(1.2) },
  { type: 'api-request', timestamp: iso(1.3) },
  { type: 'custom-title', customTitle: 'x' },
  { type: 'user', timestamp: iso(3), message: { content: env('tiller (r)', 'Old instruction') } },
  { type: 'user', timestamp: iso(3.5), message: { content: env('sib (s)', 'old sibling note') } },
  { type: 'assistant', message: { content: [{ type: 'text', text: 'Thinking it over.' }] } },
  { type: 'user', timestamp: iso(4), message: { content: env('tiller (r)', 'Also cover tests.', 'Zz9') } },
  { type: 'user', timestamp: iso(4.1), message: { content: env('sib (s)', 'hi from s') } },
  { type: 'user', timestamp: iso(5), message: { content: 'typed by human' } },
  // Lines the harness injects, as Claude writes them: none is the human's.
  { type: 'user', isMeta: true, origin: { kind: 'peer', from: 'adc38fb846cea00a2' }, timestamp: iso(5.1), message: { content: 'Another Claude session sent a message:\n<agent-message from="general-purpose">report</agent-message>' } },
  { type: 'user', origin: { kind: 'task-notification' }, timestamp: iso(5.2), message: { content: [{ type: 'text', text: '<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>' }] } },
  { type: 'user', timestamp: iso(5.3), message: { content: '<command-name>/model</command-name>\n<command-message>model</command-message>' } },
  { type: 'user', isMeta: true, timestamp: iso(5.3), message: { content: '<local-command-caveat>Caveat: generated by local commands</local-command-caveat>' } },
  { type: 'user', timestamp: iso(5.4), message: { content: '<local-command-stdout>Set model to opus</local-command-stdout>' } },
  { type: 'user', timestamp: iso(5.5), message: { content: [{ type: 'text', text: '[Request interrupted by user]' }] } },
  { type: 'assistant', timestamp: iso(9), message: { content: [{ type: 'text', text: 'Done.' }, { type: 'tool_use', name: 'mcp__tiller__report_outcome', input: {} }] } },
);

describe('buildConversation', () => {
  const c = buildConversation({ id: 'c', parentId: 'r', prompt: 'Build the thing.\n', createdAt: at(0) }, records, parseTranscript(claude, 'claude'));

  it('stitches the records and the subject\'s own turns in time order', () => {
    expect(view(c)).toEqual([
      ['brief', 'r', 'Build the thing.', 0], // the transcript's copy is dropped
      ['turn', 'c', 'Starting.', 1],
      ['message', 'c', 'Started', 1.5],
      ['turn', 'r', 'Old instruction', 3], // a legacy envelope from the parent
      ['turn', 'c', 'Thinking it over.', 3.5], // no timestamp: inherits the previous entry's
      ['message', 'r', 'Also cover tests.', 4], // placed at its delivery; its envelope is dropped
      ['turn', 'human', 'typed by human', 5],
      ['message', 'tiller', 'No hook event for 7m.', 6],
      ['message', 'tiller', '2 of 2 finished', 7],
      ['message', 'c', undefined, 8], // outbound before text was recorded: a placeholder
      ['turn', 'c', 'Done.', 9],
      ['outcome', 'c', 'succeeded', 10],
      ['event', 'c', 'merged tl/c into main', 11],
    ]);
    expect(c).toMatchObject({ a: 'r', b: 'c', relation: 'parent', titles: { c: 'Coalesce probes' } });
  });

  it('keeps both times and the delivery of a queued message, and the label of a notice', () => {
    expect(c.items.find((i) => i.kind === 'message' && i.messageId === 'm-down')).toEqual({ kind: 'message', at: at(4), sentAt: at(2), from: 'r', to: 'c', text: 'Also cover tests.', messageId: 'm-down', delivery: 'delivered' });
    expect(c.items.find((i) => i.kind === 'message' && i.messageId === 'm-n1')).toMatchObject({ label: 'tiller (child c "Coalesce probes" no activity)' });
  });

  it('keeps tool calls on turns, and an outcome item uses the event time', () => {
    expect(c.items.find((i) => i.kind === 'turn' && i.text === 'Done.')).toMatchObject({ tools: ['mcp__tiller__report_outcome'] });
    expect(c.items.find((i) => i.kind === 'outcome')).toEqual({ kind: 'outcome', at: at(10), from: 'c', outcome: { outcome: 'succeeded', summary: 'probes coalesced', gate: 'passed', at: at(10) } });
  });

  it('shows a notice only in the conversations of the children it is about', () => {
    const s = buildConversation({ id: 's', parentId: 'r', createdAt: at(0) }, records, []);
    expect(view(s)).toEqual([['message', 'tiller', '2 of 2 finished', 7]]);
  });

  it('returns the records alone when there is no transcript', () => {
    const bare = buildConversation({ id: 'c', parentId: 'r', prompt: 'Build the thing.', createdAt: at(0) }, records, []);
    expect(bare.items.map((i) => i.kind)).toEqual(['brief', 'message', 'message', 'message', 'message', 'message', 'outcome', 'event']);
  });

  it('a root\'s "With you" hides its children\'s envelopes, recorded or not (Codex transcript)', () => {
    const codex = jsonl(
      { type: 'codex_session', version: 1, threadId: 't-1' },
      { type: 'user', timestamp: iso(0.01), message: { role: 'user', content: [{ type: 'text', text: 'Plan the work' }] } },
      { type: 'assistant', timestamp: iso(1), message: { role: 'assistant', content: [{ type: 'text', text: 'Spawning.' }, { type: 'tool_use', name: 'mcp__tl_3f2a__send', input: null }] } },
      { type: 'user', timestamp: iso(1.6), message: { role: 'user', content: [{ type: 'text', text: env('Coalesce probes (c)', 'Started') }] } },
      { type: 'user', timestamp: iso(1.7), message: { role: 'user', content: [{ type: 'text', text: env('Coalesce probes (c)', 'an old report') }] } },
      { type: 'user', timestamp: iso(6.1), message: { role: 'user', content: [{ type: 'text', text: env('tiller (child c "Coalesce probes" no activity)', 'No hook event for 7m.') }] } },
      { type: 'user', timestamp: iso(12), message: { role: 'user', content: [{ type: 'text', text: env('human', 'how is it going?') }] } },
    );
    const root = buildConversation({ id: 'r', parentId: null, prompt: 'Plan the work', createdAt: at(0) }, records, parseTranscript(codex, 'codex'));
    expect(root).toMatchObject({ a: 'human', b: 'r' });
    expect(view(root)).toEqual([
      ['brief', 'human', 'Plan the work', 0],
      ['turn', 'r', 'Spawning.', 1],
      ['turn', 'human', 'how is it going?', 12], // a legacy envelope from the human is kept
    ]);
  });

  it('reads a Pi transcript\'s active branch', () => {
    const pi = jsonl(
      { type: 'session', version: 3, id: 'sess', timestamp: iso(0) },
      { type: 'message', id: 'a1', parentId: null, message: { role: 'user', content: 'Build the thing.', timestamp: at(0.01) } },
      { type: 'message', id: 'a2', parentId: 'a1', message: { role: 'assistant', content: [{ type: 'text', text: 'abandoned' }], timestamp: at(0.5) } },
      { type: 'message', id: 'a3', parentId: 'a1', message: { role: 'assistant', content: [{ type: 'text', text: 'On it.' }, { type: 'toolCall', name: 'tiller_send', arguments: {} }], timestamp: at(1) } },
      { type: 'message', id: 'a4', parentId: 'a3', message: { role: 'user', content: env('tiller (r)', 'Also cover tests.'), timestamp: at(4) } },
    );
    const c = buildConversation({ id: 'c', parentId: 'r', prompt: 'Build the thing.', createdAt: at(0) }, parseRecords(events.slice(0, 5)), parseTranscript(pi, 'pi'));
    expect(view(c)).toEqual([
      ['brief', 'r', 'Build the thing.', 0],
      ['turn', 'c', 'On it.', 1],
      ['message', 'c', 'Started', 1.5],
      ['message', 'r', 'Also cover tests.', 4],
    ]);
    expect(c.items[1]).toMatchObject({ tools: ['tiller_send'] });
  });

  it('drops a recorded message\'s envelope despite CRLF and trailing-space differences', () => {
    const r = parseRecords([ev(1, 'send', 'c', { from: 'r', outcome: 'delivered', messageId: 'm', text: 'line one  \r\nline two\r\n' })]);
    const c = buildConversation({ id: 'c', parentId: 'r', prompt: 'go\r\n', createdAt: at(0) }, r, [
      { role: 'user', at: at(0), text: 'go' },
      { role: 'user', at: at(1), text: env('tiller (r)', 'line one\nline two  ').replace(/\n/g, '\r\n') },
    ]);
    expect(view(c)).toEqual([['brief', 'r', 'go', 0], ['message', 'r', 'line one  \r\nline two\r\n', 1]]);
  });

  it('drops an envelope whose recorded text was cut, by its prefix', () => {
    const r = parseRecords([ev(1, 'send', 'c', { from: 'r', outcome: 'delivered', messageId: 'm', text: 'abc', textCut: true })]);
    const c = buildConversation({ id: 'c', parentId: 'r', createdAt: at(0) }, r, [{ role: 'user', at: at(1), text: env('tiller (r)', 'abcdef') }]);
    expect(view(c)).toEqual([['message', 'r', 'abc', 1]]);
  });
});

describe('buildPeerConversation', () => {
  it('holds only the messages between the two, from the records', () => {
    const p = buildPeerConversation('c', 's', records);
    expect(p).toMatchObject({ a: 'c', b: 's', relation: 'peer' });
    expect(view(p)).toEqual([['message', 's', 'hi from s', 2.5]]);
  });
});

describe('parseRecords', () => {
  it('drops events of the wrong shape and keeps only known outcome fields', () => {
    const r = parseRecords([
      { ts: 'soon', type: 'send', id: 'c', from: 'r', outcome: 'delivered', messageId: 'm1' } as unknown as SessionEvent,
      ev(1, 'send', 'c', { from: 'r', outcome: 'teleported', messageId: 'm2' }),
      ev(1, 'send', 'c', { from: 'r', outcome: 'delivered', messageId: 'm3', text: 42, about: [1] }),
      ev(2, 'settle', 'c', { messageId: 7, outcome: 'delivered' }),
      ev(3, 'outcome', 'c', { outcome: 'maybe' }),
      ev(4, 'outcome', 'c', { outcome: 'failed', note: 'x', changedFiles: 'a.ts', html: '<b>' }),
    ]);
    expect(r.sends).toEqual([{ ts: at(1), to: 'c', from: 'r', outcome: 'delivered', messageId: 'm3' }]);
    expect(r.settles.size).toBe(0);
    expect(r.outcomes).toEqual([{ ts: at(4), id: 'c', outcome: { outcome: 'failed', note: 'x', at: at(4) } }]);
  });
});

describe('parseEnvelope', () => {
  it('reads the label, reply-to and a multi-line body', () => {
    expect(parseEnvelope('--- TL MESSAGE n1 ---\nfrom: tiller (n-96530325)\nreply-to: n-96530325\nline one\n\nline two\n--- END TL MESSAGE n1 ---'))
      .toEqual({ label: 'tiller (n-96530325)', replyTo: 'n-96530325', body: 'line one\n\nline two' });
  });

  it('reads the steer line apart from the body', () => {
    expect(parseEnvelope('--- TL MESSAGE n1 ---\nfrom: p (p)\nreply-to: p\nsteer: the sender interrupted your turn on purpose to deliver this now\nstop\n--- END TL MESSAGE n1 ---'))
      .toEqual({ label: 'p (p)', replyTo: 'p', body: 'stop', steer: true });
  });

  it('keeps the ambiguous daemon label whole, and rejects a mismatched nonce or a partial envelope', () => {
    expect(parseEnvelope(env('tiller (child n-x "a (b)" stopped: exited)', 'No further details.'))?.label).toBe('tiller (child n-x "a (b)" stopped: exited)');
    expect(parseEnvelope('--- TL MESSAGE n1 ---\nfrom: p (p)\nreply-to: p\nhi\n--- END TL MESSAGE n2 ---')).toBeUndefined();
    expect(parseEnvelope(`please read: ${env('p (p)', 'hi')}`)).toBeUndefined();
  });
});

describe('buildIndex', () => {
  const archived = { id: 's', rootId: 'r', parentId: 'r', title: 'Sibling', cwd: '/', createdAt: at(0.5), closedAt: at(20), outcome: { outcome: 'failed', at: at(19) } } as ArchivedNode;
  const nodes = new Map<string, TreeNode>([
    ['r', { title: 'tiller', parentId: null, createdAt: at(-1), live: true }],
    ['c', { title: 'Coalesce probes', parentId: 'r', createdAt: at(0), live: true, outcome: 'succeeded' }],
    ['s', { title: 'Sibling', parentId: 'r', createdAt: at(0.5), live: false, archived, outcome: 'failed' }],
  ]);

  it('lists the human, then the children most recent first, counting delivered messages only', () => {
    expect(buildIndex('r', nodes, records)).toEqual([
      { id: 'r', relation: 'parent', counterpart: 'human', title: 'You', live: true, messages: 0 },
      { id: 'c', relation: 'child', counterpart: 'c', title: 'Coalesce probes', live: true, messages: 6, lastAt: at(10), outcome: 'succeeded' },
      { id: 's', relation: 'child', counterpart: 's', title: 'Sibling', live: false, archived, messages: 1, lastAt: at(7), outcome: 'failed' },
    ]);
  });

  it('lists a child\'s parent, then its peers', () => {
    expect(buildIndex('c', nodes, records)).toEqual([
      { id: 'c', relation: 'parent', counterpart: 'r', title: 'tiller', live: true, messages: 6, lastAt: at(8.5) },
      { id: 'c', with: 's', relation: 'peer', counterpart: 's', title: 'Sibling', live: false, archived, messages: 1, lastAt: at(2.5) },
    ]);
  });
});
